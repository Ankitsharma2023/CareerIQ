"""Attach an outcome statement to a score, when the data supports one.

"You scored 62" is not information. What a candidate wants to know is what
happened to other resumes that scored 62 — and that is answerable, because
evals/public_dataset.py scored 1,759 resume-job pairs that carry independent
human labels.

The answer is mostly "nothing distinguishable", and this module says so rather
than dressing the base rate up as a finding. Of seven score bands in the
measured data, one has a confidence interval that excludes the overall good-fit
rate. Reporting the other six as though they predicted something would tell a
user their score means more than it does, which is the failure mode this whole
upgrade has been aimed at.

The table is generated by evals/calibration.py and committed as data. It is
loaded once and cached: a missing or malformed file degrades to "no calibration
available" rather than failing an analysis, because a resume report is still
worth returning without it.
"""
from __future__ import annotations

import json
import logging
from functools import lru_cache
from pathlib import Path

logger = logging.getLogger(__name__)

TABLE_PATH = Path(__file__).resolve().parent.parent / "data" / "calibration.json"


@lru_cache(maxsize=1)
def _table() -> dict | None:
    try:
        return json.loads(TABLE_PATH.read_text(encoding="utf-8"))
    except FileNotFoundError:
        logger.info("No calibration table at %s; scores will be uncalibrated", TABLE_PATH)
        return None
    except (OSError, json.JSONDecodeError):
        logger.exception("Calibration table at %s could not be read", TABLE_PATH)
        return None


def describe(score: float) -> dict | None:
    """What happened to labelled resumes that scored in this band.

    Returns ``None`` when there is no table, or when the score falls outside
    every measured band — the honest answer there is silence, not the nearest
    band's rate applied to a score the data never saw.
    """
    table = _table()
    if not table:
        return None

    for band in table.get("bands", []):
        if band["low"] <= score < band["high"] or (
            band["high"] >= 100 and score >= band["low"]
        ):
            return {
                "band_low": band["low"],
                "band_high": band["high"],
                "good_fit_rate": band["good_fit_rate"],
                "ci_low": band["ci_low"],
                "ci_high": band["ci_high"],
                "sample_size": band["n"],
                "base_rate": table["base_rate"],
                "informative": band["informative"],
                "documents": table["documents"],
            }

    return None
